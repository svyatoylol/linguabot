    public IReadOnlyList<ScenarioDefinition> GetAll() => _scenarios;

    public ScenarioDefinition? GetById(string id)
    {
        if (string.IsNullOrWhiteSpace(id)) return _scenarios[0];

        // Нормализация возможных синонимов / алиасов
        var normalized = id.Trim().ToLowerInvariant() switch
        {
            "shopping" => "shop",
            "trip_planning" => "trip",
            "job_interview" => "interview",
            "business_meeting" => "business-meeting",
            "movie_discussion" => "film",
            _ => id.Trim().ToLowerInvariant()
        };

        return _scenarios.FirstOrDefault(s => s.Id.Equals(normalized, StringComparison.OrdinalIgnoreCase))
            ?? _scenarios.FirstOrDefault(s => s.Id.Equals(id, StringComparison.OrdinalIgnoreCase))
            ?? _scenarios[0];
    }
